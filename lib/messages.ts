export const messages: Record<Locale, Dict> = { ru, en, kk };

const STORED: Record<string, keyof Dict> = {
  slugTaken: "errSlugTaken",
  eventMissing: "errEventMissing",
  alreadyRegistered: "errAlready",
};

export function errorText(locale: Locale, code: string) {
  const dict = messages[locale];
  const key = (STORED[code] || code) as keyof Dict;
  const value = dict[key];
  return typeof value === "string" ? value : code;
}

export function fill(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

export function countryLabel(locale: Locale, value: string) {
  const code = isCountryId(value) ? value : LEGACY_COUNTRY[value];
  if (!code) return value;
  return messages[locale].countries[code];
}

